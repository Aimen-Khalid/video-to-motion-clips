// Builds the browser preview files for the review board:
//   ../board/motion/styles.bundle.js  every style module wrapped for the browser
//   ../board/motion/data.js           beats, durations and voice envelopes per clip
// Usage: node build.js
const fs = require("fs"), path = require("path"), { execFileSync } = require("child_process");
const ROOT = __dirname, OUT = path.join(ROOT, "..", "board", "motion");
fs.mkdirSync(OUT, { recursive: true });
const FPS = 30;
const spec = JSON.parse(fs.readFileSync(path.join(ROOT, "spec.json"), "utf8"));

// ---- styles bundle ----
let bundle = `/* generated by build.js */\nwindow.MOTION_STYLES = window.MOTION_STYLES || {};\n` +
  `window.__motionRequire = function(name){ if(name === "@napi-rs/canvas") return { createCanvas: function(w,h){ var c=document.createElement("canvas"); c.width=w; c.height=h; return c; } }; throw new Error("not available in browser: "+name); };\n`;
const built = [];
for (const c of spec.clips) {
  const f = path.join(ROOT, "styles", c.styleFile + ".js");
  if (!fs.existsSync(f) || built.includes(c.styleFile)) continue;
  let code = fs.readFileSync(f, "utf8");
  // a style that's mid-edit must never break the whole bundle: fall back to its last good copy
  const good = path.join(ROOT, ".good", c.styleFile + ".js");
  try { new Function("module", "exports", "require", code); fs.mkdirSync(path.dirname(good), { recursive: true }); fs.writeFileSync(good, code); }
  catch (e) { console.warn("skipping broken", c.styleFile, e.message); if (!fs.existsSync(good)) continue; code = fs.readFileSync(good, "utf8"); }
  bundle += `\n;(function(){ var module={exports:{}}, exports=module.exports, require=window.__motionRequire;\n${code}\nwindow.MOTION_STYLES[${JSON.stringify(c.styleFile)}]=module.exports; })();\n`;
  built.push(c.styleFile);
}
fs.writeFileSync(path.join(OUT, "styles.bundle.js"), bundle);

// ---- optional caption templates (ported from Animora): renderer, templates and word timings ----
const CAPDIR = path.join(ROOT, "captions");
if (fs.existsSync(path.join(CAPDIR, "captions.js"))) {
  fs.copyFileSync(path.join(CAPDIR, "captions.js"), path.join(OUT, "captions.js"));
  const tpl = JSON.parse(fs.readFileSync(path.join(CAPDIR, "templates.json"), "utf8"));
  const words = fs.existsSync(path.join(CAPDIR, "words.json")) ? JSON.parse(fs.readFileSync(path.join(CAPDIR, "words.json"), "utf8")) : {};
  const fontsUrl = fs.readFileSync(path.join(CAPDIR, "fonts-google.txt"), "utf8").split(/\s+/).find(x => x.startsWith("https://")) || "";
  fs.writeFileSync(path.join(OUT, "captions-data.js"), "/* generated by build.js */\nwindow.CAPTION_TEMPLATES = " + JSON.stringify(tpl) +
    ";\nwindow.CAPTION_WORDS = " + JSON.stringify(words) + ";\nwindow.CAPTION_FONTS_URL = " + JSON.stringify(fontsUrl) + ";\n");
  console.log("captions: templates + words written");
}

// ---- data: beats + voice envelope (0..255 per frame) ----
function envelope(audio, dur) {
  const raw = execFileSync("ffmpeg", ["-v", "error", "-i", audio, "-f", "s16le", "-ac", "1", "-ar", "16000", "-"], { maxBuffer: 1 << 28 });
  const s = new Int16Array(raw.buffer, raw.byteOffset, raw.length >> 1);
  const per = Math.round(16000 / FPS), n = Math.ceil(dur * FPS), env = new Float32Array(n);
  for (let f = 0; f < n; f++) { let sum = 0, c = 0; for (let i = f * per; i < (f + 1) * per && i < s.length; i++) { sum += s[i] * s[i]; c++; } env[f] = c ? Math.sqrt(sum / c) / 32768 : 0; }
  const sorted = Array.from(env).sort((a, b) => a - b), p95 = sorted[Math.floor(n * .95)] || 1;
  let prev = 0; const out = [];
  for (let f = 0; f < n; f++) { const v = Math.min(1, env[f] / p95); prev = v > prev ? prev + (v - prev) * .6 : prev + (v - prev) * .15; out.push(Math.round(prev * 255)); }
  return out;
}
// The preview must hand style modules exactly what engine.js hands them: the same frame size and meta.
const sizeFor = fmt => (fmt === "16:9" ? [1920, 1080] : [1080, 1920]);
const data = { source: spec.source, meta: { label: spec.label || "", credit: spec.credit || "" }, clips: {} };
for (const c of spec.clips) {
  const [W, H] = sizeFor(c.format);
  data.clips[c.n] = { n: c.n, W, H, format: c.format || "9:16", dur: c.dur, styleFile: c.styleFile, style: c.style, beats: c.beats, ready: built.includes(c.styleFile),
    env: envelope(path.join(ROOT, c.audio), c.dur) };
}
fs.writeFileSync(path.join(OUT, "data.js"), "/* generated by build.js */\nwindow.MOTION_DATA = " + JSON.stringify(data) + ";\n");
console.log("styles:", built.join(", "));
console.log("bundle", fs.statSync(path.join(OUT, "styles.bundle.js")).size, "data", fs.statSync(path.join(OUT, "data.js")).size);
